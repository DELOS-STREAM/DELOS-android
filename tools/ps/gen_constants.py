#!/usr/bin/env python3
"""Generates app/src/main/java/com/limelight/ps/PsConstants.kt from docs/research/ps-remote-play-constants.md.

Every table is a hex block under a `## NAME` heading ("00: be ce ..."). The script checks the SHA-256 of each table that
the document lists under "Checksums" and fails on a mismatch, so a copy error cannot reach the app.
"""
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'docs/research/ps-remote-play-constants.md'
OUT = ROOT / 'app/src/main/java/com/limelight/ps/PsConstants.kt'


def main():
    text = SRC.read_text()
    tables = {}
    for name, block in re.findall(r'^## ([A-Z0-9_]+)\n.*?```\n(.*?)```', text, re.S | re.M):
        data = bytearray()
        for line in block.strip().splitlines():
            data += bytes.fromhex(line.split(':', 1)[1])
        tables[name] = bytes(data)
    for name, digest in re.findall(r'^\| ([A-Z0-9_]+) \| `([0-9a-f]{64})` \|', text, re.M):
        actual = hashlib.sha256(tables[name]).hexdigest()
        if actual != digest:
            sys.exit(f'{name}: checksum {actual} != {digest}')
    lines = [
        'package com.limelight.ps',
        '',
        '/**',
        ' * Interoperability constants of PlayStation Remote Play, generated by tools/ps/gen_constants.py from',
        ' * docs/research/ps-remote-play-constants.md (checksums verified). They were extracted from Sony\'s Remote Play client by',
        ' * third parties; the owner decided on 2026-11-21 that DELOS ships them (open source, not sold). Do not edit by hand.',
        ' */',
        'internal object PsConstants {',
    ]
    for name, data in tables.items():
        lines.append(f'    val {name}: ByteArray by lazy {{ PsHex.decode("{data.hex()}") }}')
    lines.append('}')
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(lines) + '\n')
    print(OUT, {k: len(v) for k, v in tables.items()})


main()
